export const DEFAULT_SCRIPT_EXTRACT_PROMPT = `# 拆剧本 · 单段提取（开源，可改）

你正在看视频的一张定格画面。图上（或工具给出的 caption）有时间戳。只写**这一瞬间看见的东西**，不要补看不见的前后剧情，不要听（当前模型没有音频）。

## 输出一块「节拍」，不要解释

\`\`\`
[HH:MM:SS] 节拍
△ 画面：谁、在哪、做什么、镜头怎么动（只写看见的）
【字幕】画面上的字（原文照抄；没有就不写这一行）
【画面未见对白】
\`\`\`

若能从字幕或口型对应到说话人，把最后一行换成：

\`\`\`
角色名：台词原文
\`\`\`

## 规则

1. 时间戳必须用工具给出的那一帧，不要四舍五入到整场。
2. 不编造听不见的对白；没字幕就写 \`【画面未见对白】\`。
3. 不把后面几秒的剧情写进这一拍。
4. 专有名词、招牌、字幕原文照抄，不要意译。
5. 宁可朴素、完整，不要文学概括。`

export const DEFAULT_SCRIPT_MERGE_PROMPT = `# 拆剧本 · 节拍合并（开源，可改）

输入是按固定时间间隔抽出的「节拍」列表。相邻节拍经常在讲同一件事。请合并成一场接一场的完整剧本。

## 合并原则

1. **同一事件 / 同一场景 / 同一动作**的连续节拍合成一场。新一场的时间戳 = 被合并的第一拍时间。
2. 地点、人物关系、动作方向、镜头明显切换时，另起一场。
3. 画面描述去重：连续重复的△只保留一份更完整的；**只出现一次的细节、道具、字幕一律保留**。
4. 台词去重：同一句字幕连续出现只写一次；有推进的对白按时间顺序全留。
5. 不编造。看不见的对白写 \`【画面未见对白】\`。
6. 合并后时间轴仍从第一拍覆盖到最后一拍，场次编号 \`1-1\`、\`1-2\` 递增。
7. 只输出剧本正文，不要过程说明。

## 输出格式

\`\`\`
[HH:MM:SS] 1-1 地点 日/内
△ 画面（谁、在哪、做什么、镜头怎么动）
【字幕】原文
角色名：台词

[HH:MM:SS] 1-2 地点 日/内
△ 画面
【画面未见对白】
\`\`\``

export function resolveScriptPrompt(custom: string | undefined, fallback: string): string {
  const text = custom?.trim()
  return text ? text : fallback
}
